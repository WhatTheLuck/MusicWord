"""Build the browser's offline library from the HW-Music Pattern folder."""

import argparse
import csv
import json
from pathlib import Path, PureWindowsPath


def read_rows(path):
    with path.open(encoding="utf-8-sig", newline="") as source:
        return list(csv.DictReader(source))


def export_bank(source):
    metadata = json.loads((source / "patterns_bank" / "patterns_info.json").read_text(encoding="utf-8"))
    words = []
    for item in metadata:
        rows = read_rows(source.joinpath(*PureWindowsPath(item["processed_csv"]).parts))
        if not rows or {row["tpb"] for row in rows} != {"240"}:
            raise ValueError(f"Expected a nonempty 240-tick pattern: {item['pattern_name']}")
        if {row["original_chord"] for row in rows} != {"C-maj7"}:
            raise ValueError(f"Expected C-maj7 source harmony: {item['pattern_name']}")
        notes = [
            [int(row["start"]), int(row["dur"]), int(row["pitch"]), int(row["vel"])]
            for row in rows
            if int(row["dur"]) > 0
        ]
        words.append([item["pattern_id"], item["pattern_name"], sorted(notes)])
    example = []
    for row in read_rows(source / "pattern_events.csv"):
        root, quality = row["chord_name"].strip().split("-")
        example.append([root, "dom7" if quality == "7" else quality, int(row["beat_len"]), int(row["octave"])])
    return {"words": words, "example": example}


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    bank = export_bank(parser.parse_args().source)
    output = Path(__file__).with_name("bank.js")
    rows = ",\n".join(json.dumps(word, ensure_ascii=False, separators=(",", ":")) for word in bank["words"])
    example = json.dumps(bank["example"], ensure_ascii=False, separators=(",", ":"))
    output.write_text(
        "// Generated by import-bank.py from the HW-Music Pattern processed CSVs.\n"
        + "globalThis.LEGO_LIBRARY = {words: [\n" + rows + "\n], example: " + example + "};\n",
        encoding="utf-8",
    )
    print(f"{len(bank['words'])} words written to {output}")
